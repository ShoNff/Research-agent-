// Build step: turn the repo's editions/ folder into the web app's daily paper.
//
// Source of truth is editions/YYYY-MM-DD/edition.json (written and validated
// by the research-paper pipeline). This script reads every edition and emits
// lib/editions.generated.ts — newest first — for the front page and the
// /paper archive. Same defensive posture as build-library.mjs: if editions/
// isn't reachable (e.g. a Vercel build scoped to web/), leave the committed
// output untouched.

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB = join(HERE, "..");
const REPO = join(WEB, "..");
const EDITIONS_DIR = join(REPO, "editions");
const OUT_MODULE = join(WEB, "lib", "editions.generated.ts");

const DATE_DIR = /^\d{4}-\d{2}-\d{2}$/;

function main() {
  if (!existsSync(EDITIONS_DIR)) {
    if (existsSync(OUT_MODULE)) {
      console.warn(
        `[build-editions] editions/ not found at ${EDITIONS_DIR} — leaving committed output untouched.`
      );
      return;
    }
    // First build with no editions yet: emit an empty module so imports work.
    mkdirSync(dirname(OUT_MODULE), { recursive: true });
    writeFileSync(
      OUT_MODULE,
      "// AUTO-GENERATED by scripts/build-editions.mjs — do not edit by hand.\nexport const EDITIONS = [] as const;\n"
    );
    console.log("[build-editions] no editions/ dir — wrote empty module");
    return;
  }

  const editions = [];
  for (const entry of readdirSync(EDITIONS_DIR)) {
    if (!DATE_DIR.test(entry)) continue;
    const dir = join(EDITIONS_DIR, entry);
    if (!statSync(dir).isDirectory()) continue;
    const jsonPath = join(dir, "edition.json");
    if (!existsSync(jsonPath)) continue;
    try {
      const edition = JSON.parse(readFileSync(jsonPath, "utf8"));
      if (!edition.date) edition.date = entry;
      editions.push(edition);
    } catch {
      console.warn(`[build-editions] skipping ${entry}: invalid edition.json`);
    }
  }

  editions.sort((a, b) => (a.date < b.date ? 1 : -1));

  const banner =
    "// AUTO-GENERATED by scripts/build-editions.mjs — do not edit by hand.\n" +
    "// Regenerated before every dev/build run from the repo's editions/ folder.\n";
  const body = `export const EDITIONS = ${JSON.stringify(editions, null, 2)} as const;\n`;

  mkdirSync(dirname(OUT_MODULE), { recursive: true });
  writeFileSync(OUT_MODULE, banner + body);
  console.log(`[build-editions] wrote ${editions.length} edition(s) to editions.generated.ts`);
}

main();
